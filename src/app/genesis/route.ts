    "});",
    "",
    "if (!challengeRes.ok) {",
    "  const err = await challengeRes.text();",
    '  console.error("[-] Failed to fetch challenge:", err);',
    "  process.exit(1);",
    "}",
    "",
    "const challenge = await challengeRes.json();",
