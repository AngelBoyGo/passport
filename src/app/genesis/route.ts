    "  subject_commitment: prov.subject_commitment,",
    "  did: prov.did,",
    "  api_key: prov.api_key,",
    "  public_key: pubKeyHex,",
    "  private_key: privKeyHex,",
    "  initial_credits: prov.initial_credits,",
    "  created_at: new Date().toISOString(),",
